-- CSCI 341 Assignment 3, Part 1. PostgreSQL. Run in a dedicated database.
-- Plain SQL: executable by psql, pgAdmin, or SQLAlchemy.
BEGIN;

CREATE TABLE app_user (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    given_name TEXT NOT NULL,
    surname TEXT NOT NULL,
    email TEXT NOT NULL CONSTRAINT uq_app_user_email UNIQUE,
    affiliation TEXT NOT NULL,
    country TEXT NOT NULL,
    phone_number TEXT NOT NULL
);

CREATE TABLE author (
    author_id INTEGER PRIMARY KEY REFERENCES app_user(user_id) ON DELETE CASCADE,
    orcid TEXT
);

CREATE TABLE author_research_area (
    author_id INTEGER NOT NULL REFERENCES author(author_id) ON DELETE CASCADE,
    area_label TEXT NOT NULL,
    PRIMARY KEY (author_id, area_label)
);

CREATE TABLE reviewer (
    reviewer_id INTEGER PRIMARY KEY REFERENCES app_user(user_id) ON DELETE CASCADE,
    years_experience INTEGER NOT NULL CHECK (years_experience >= 0)
);

CREATE TABLE reviewer_expertise (
    reviewer_id INTEGER NOT NULL REFERENCES reviewer(reviewer_id) ON DELETE CASCADE,
    area_label TEXT NOT NULL,
    PRIMARY KEY (reviewer_id, area_label)
);

CREATE TABLE conference (
    conference_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    acronym TEXT NOT NULL,
    description TEXT NOT NULL,
    city TEXT NOT NULL,
    country TEXT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    submission_deadline DATE NOT NULL,
    review_deadline DATE NOT NULL,
    CONSTRAINT ck_conference_dates CHECK (end_date >= start_date)
);

CREATE TABLE conference_host (
    conference_id INTEGER NOT NULL REFERENCES conference(conference_id) ON DELETE CASCADE,
    host_name TEXT NOT NULL,
    PRIMARY KEY (conference_id, host_name)
);

CREATE TABLE conference_reviewer (
    conference_id INTEGER NOT NULL REFERENCES conference(conference_id) ON DELETE CASCADE,
    reviewer_id INTEGER NOT NULL REFERENCES reviewer(reviewer_id) ON DELETE RESTRICT,
    PRIMARY KEY (conference_id, reviewer_id)
);

CREATE TABLE track (
    track_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conference_id INTEGER NOT NULL REFERENCES conference(conference_id) ON DELETE RESTRICT,
    name TEXT NOT NULL,
    description TEXT NOT NULL,
    research_area TEXT NOT NULL,
    coordinator_id INTEGER NOT NULL REFERENCES reviewer(reviewer_id) ON DELETE RESTRICT,
    CONSTRAINT fk_track_coordinator_pool FOREIGN KEY (conference_id, coordinator_id)
        REFERENCES conference_reviewer(conference_id, reviewer_id) ON DELETE RESTRICT
);

CREATE TABLE conference_session (
    session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conference_id INTEGER NOT NULL REFERENCES conference(conference_id) ON DELETE RESTRICT,
    title TEXT NOT NULL,
    session_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    room_label TEXT NOT NULL,
    chair_id INTEGER NOT NULL REFERENCES reviewer(reviewer_id) ON DELETE RESTRICT,
    CONSTRAINT ck_session_times CHECK (end_time > start_time),
    CONSTRAINT fk_session_chair_pool FOREIGN KEY (conference_id, chair_id)
        REFERENCES conference_reviewer(conference_id, reviewer_id) ON DELETE RESTRICT
);

CREATE TABLE paper (
    paper_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id INTEGER NOT NULL REFERENCES track(track_id) ON DELETE RESTRICT,
    title TEXT NOT NULL,
    abstract TEXT NOT NULL,
    submission_date DATE NOT NULL,
    status TEXT NOT NULL CONSTRAINT ck_paper_status
        CHECK (status IN ('submitted', 'under review', 'accepted', 'rejected', 'withdrawn')),
    session_id INTEGER REFERENCES conference_session(session_id) ON DELETE SET NULL
);

CREATE TABLE paper_keyword (
    paper_id INTEGER NOT NULL REFERENCES paper(paper_id) ON DELETE CASCADE,
    keyword TEXT NOT NULL,
    PRIMARY KEY (paper_id, keyword)
);

CREATE TABLE paper_author (
    paper_id INTEGER NOT NULL REFERENCES paper(paper_id) ON DELETE CASCADE,
    author_id INTEGER NOT NULL REFERENCES author(author_id) ON DELETE RESTRICT,
    author_position INTEGER NOT NULL CHECK (author_position > 0),
    is_corresponding BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (paper_id, author_id),
    CONSTRAINT uq_paper_author_position UNIQUE (paper_id, author_position)
);

-- Optional rule partially enforced: at MOST one corresponding author.
-- At LEAST one must be maintained by the application if it chooses to enforce it.
CREATE UNIQUE INDEX uq_paper_one_corresponding
    ON paper_author(paper_id) WHERE is_corresponding;

CREATE TABLE paper_version (
    paper_id INTEGER NOT NULL REFERENCES paper(paper_id) ON DELETE CASCADE,
    version_no INTEGER NOT NULL CHECK (version_no > 0),
    file_location TEXT NOT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    change_note TEXT,
    PRIMARY KEY (paper_id, version_no)
);

CREATE TABLE review (
    review_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paper_id INTEGER NOT NULL REFERENCES paper(paper_id) ON DELETE CASCADE,
    reviewer_id INTEGER NOT NULL REFERENCES reviewer(reviewer_id) ON DELETE RESTRICT,
    overall_score INTEGER NOT NULL CHECK (overall_score BETWEEN 1 AND 5),
    recommendation TEXT NOT NULL CHECK (recommendation IN ('accept', 'reject')),
    comments_for_authors TEXT NOT NULL CHECK (length(btrim(comments_for_authors)) > 0),
    confidential_comments TEXT,
    review_submission_date DATE NOT NULL,
    CONSTRAINT uq_review_paper_reviewer UNIQUE (paper_id, reviewer_id)
);

CREATE INDEX ix_track_conference ON track(conference_id);
CREATE INDEX ix_paper_track ON paper(track_id);
CREATE INDEX ix_paper_session ON paper(session_id);
CREATE INDEX ix_paper_author_author ON paper_author(author_id);
CREATE INDEX ix_review_reviewer ON review(reviewer_id);

COMMIT;
